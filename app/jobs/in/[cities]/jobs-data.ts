export type JobListing = {
  id: string;
  title: string;
  hospital: string;
  location: string;
  experience: string;
  type: string;
  salary: string;
  skills: string[];
  postedAgo: string;
  role?: "doctor" | "nurse" | "allied" | "technician" | "non-technician" | "non-allied";
  education?: string;
};

export interface RoleInfo {
  id: string;
  label: string;
  plural: string;
  titlePrefix: string;
  descriptionPrefix: string;
}

export function getRoleInfo(roleSlug?: string): RoleInfo | null {
  if (!roleSlug) return null;
  const slug = roleSlug.toLowerCase().trim();
  switch (slug) {
    case "doctor":
      return {
        id: "doctor",
        label: "Doctor",
        plural: "Doctors",
        titlePrefix: "Doctor",
        descriptionPrefix: "verified doctor and physician",
      };
    case "nurse":
      return {
        id: "nurse",
        label: "Nurse",
        plural: "Nurses",
        titlePrefix: "Nurse",
        descriptionPrefix: "verified nursing and staff nurse",
      };
    case "allied":
      return {
        id: "allied",
        label: "Allied",
        plural: "Allied Health Professionals",
        titlePrefix: "Allied Healthcare",
        descriptionPrefix: "verified allied healthcare and clinical support",
      };
    case "technician":
      return {
        id: "technician",
        label: "Technician",
        plural: "Technicians",
        titlePrefix: "Medical Technician",
        descriptionPrefix: "verified medical and laboratory technician",
      };
    case "non-allied":
      return {
        id: "non-allied",
        label: "Non-Allied",
        plural: "Non-Allied Staff",
        titlePrefix: "Non-Allied Healthcare",
        descriptionPrefix: "verified non-allied hospital administration and operational",
      };
    case "non-technician":
      return {
        id: "non-technician",
        label: "Non-Technician",
        plural: "Non-Technician Staff",
        titlePrefix: "Non-Technician Healthcare",
        descriptionPrefix: "verified non-technician hospital support and operational",
      };
    default:
      return null;
  }
}

