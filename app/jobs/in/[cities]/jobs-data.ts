export function getJobsForCity(city: string, role?: string): JobListing[] {
  // Normalize city key match
  const cityKey = Object.keys(JOBS_BY_CITY).find(
    (k) => k.toLowerCase() === city.toLowerCase().trim()
  );

  const cityListings = cityKey ? JOBS_BY_CITY[cityKey] : generateGenericCityJobs(city);

  if (!role || role === "all") {
    return cityListings;
  }

  const filtered = cityListings.filter((job) => {
    if (role === "non-allied" || role === "non-technician") {
      return job.role === "non-allied" || job.role === "non-technician";
    }
    return job.role === role;
  });
  if (filtered.length > 0) {
    return filtered;
  }

  // If city specific didn't have that role, generate generic fallback for that role
  return generateGenericCityJobs(city, role);
}
